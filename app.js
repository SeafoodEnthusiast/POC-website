  const viewport = document.getElementById("cameraViewport");
  viewport.addEventListener("click", (e) => {
    const rect = viewport.getBoundingClientRect();
    const x = e.clientX - rect.left;
    const y = e.clientY - rect.top;
    const sq = document.getElementById("focusSquare");
    sq.style.left = `${x}px`;
    sq.style.top = `${y}px`;
    sq.classList.remove("hidden");
    sq.style.animation = "none";
    void sq.offsetWidth;
    sq.style.animation = "focusPulse 0.6s ease-out";
    setTimeout(() => sq.classList.add("hidden"), 900);
  });

  // Scan View: Zoom Slider
  document.getElementById("zoomSlider").addEventListener("input", (e) => {
    state.cameraZoom = parseFloat(e.target.value);
    document.getElementById("cameraVideo").style.transform = `scale(${state.cameraZoom})`;
    document.getElementById("cameraGhostSample").style.transform = `scale(${state.cameraZoom})`;
  });

  // Scan View: Load Sample OD / OS
  const handleLoadSampleForCurrentEye = async () => {
    const isLeft = state.selectedEye === "left";
    const samplePath = isLeft ? "./samples/RET018OS.jpg" : "./samples/RET018OD.jpg";
    const sampleKey = isLeft ? "RET018OS" : "RET018OD";
    try {
      const img = await loadImageElement(samplePath);
      openReviewWithImage(img, sampleKey);
    } catch {
      showIosAlert("Unable to load sample", "Could not load sample fundus image.");
    }
  };

