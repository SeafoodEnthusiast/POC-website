async function runQuickClinicalDemo() {
  const btn = document.getElementById("btnQuickDemoReport");
  const origHtml = btn.innerHTML;
  btn.disabled = true;
  btn.textContent = "Analyzing RET018OS & RET018OD...";

  try {
    const [osImg, odImg] = await Promise.all([
      loadImageElement("./samples/RET018OS.jpg"),
      loadImageElement("./samples/RET018OD.jpg"),
    ]);

    const [osResult, odResult] = await Promise.all([
      predictImage(osImg, "RET018OS"),
      predictImage(odImg, "RET018OD"),
    ]);

    state.leftImage = osImg;
    state.leftResult = osResult;
    state.rightImage = odImg;
    state.rightResult = odResult;
    state.examDate = new Date();

    switchView("report");
  } catch (err) {
    showIosAlert("Demo Error", err.message || "Could not load sample images.");
  } finally {
    btn.disabled = false;
    btn.innerHTML = origHtml;
  }
}

