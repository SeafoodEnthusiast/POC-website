function getCDRStatus(cdr) {
  if (cdr === null || cdr === undefined || Number.isNaN(cdr)) {
    return {
      key: "unavailable",
      rank: 0,
      label: "Not measured",
      cssClass: "status-unavailable",
      nextStepTitle: "Repeat the scan",
      nextStepBody:
        "A cup-to-disc ratio could not be measured. Retake the photo and try again.",
    };
  }
  if (cdr >= CDR_THRESHOLDS.highRiskFrom) {
    return {
      key: "highRisk",
      rank: 3,
      label: "High Risk Glaucoma",
      cssClass: "status-highrisk",
      nextStepTitle: "Prompt ophthalmology review",
      nextStepBody:
        "Contact an ophthalmologist promptly to check eye pressure, visual fields, and the optic nerve. Seek urgent care for sudden eye pain or vision loss.",
    };
  }
  if (cdr >= CDR_THRESHOLDS.suspectFrom) {
    return {
      key: "suspect",
      rank: 2,
      label: "Glaucoma Suspect",
      cssClass: "status-suspect",
      nextStepTitle: "Arrange a comprehensive eye exam",
      nextStepBody:
        "An ophthalmologist can check eye pressure, the optic nerve, and visual fields. Suspect does not mean confirmed glaucoma.",
    };
  }
  return {
    key: "normal",
    rank: 1,
    label: "Normal",
    cssClass: "status-normal",
    nextStepTitle: "Continue routine eye checks",
    nextStepBody:
      "No enlarged cup-to-disc ratio was found. A normal screening does not rule out glaucoma, so keep up regular eye exams.",
  };
}

function formatCDR(cdr) {
  if (cdr === null || cdr === undefined || Number.isNaN(cdr)) return "N/A";
  return cdr.toFixed(2);
}

function formatCapturedDate(date) {
  const opts = {
    day: "numeric",
    month: "short",
    year: "numeric",
    hour: "numeric",
    minute: "2-digit",
    hour12: true,
  };
  return "Captured " + date.toLocaleString("en-US", opts);
}

function buildReportSummary(leftResult, rightResult) {
  const leftStatus = getCDRStatus(leftResult?.verticalCDR);
  const rightStatus = getCDRStatus(rightResult?.verticalCDR);
  const overall = leftStatus.rank >= rightStatus.rank ? leftStatus : rightStatus;

  let summarySentence = "";
  if (overall.key === "unavailable") {
    summarySentence =
      "No cup-to-disc ratio could be measured for either eye. Retake the photos and try again.";
  } else if (leftStatus.key === "unavailable" || rightStatus.key === "unavailable") {
    const missing = leftStatus.key === "unavailable" ? "left" : "right";
    summarySentence = `A cup-to-disc ratio could not be measured for the ${missing} eye. Retake that photo for a complete report.`;
  } else if (leftStatus.key === rightStatus.key) {
    summarySentence =
      overall.key === "normal"
        ? "Both eyes are in the normal CDR range on this screening."
        : `Both eyes show an elevated vertical CDR (${overall.label}).`;
  } else {
    const leftWorse = leftStatus.rank > rightStatus.rank;
    const worseName = leftWorse ? "left eye" : "right eye";
    const worseCdr = formatCDR(leftWorse ? leftResult?.verticalCDR : rightResult?.verticalCDR);
    const otherCdr = formatCDR(leftWorse ? rightResult?.verticalCDR : leftResult?.verticalCDR);
    summarySentence = `The ${worseName} has the higher CDR (${worseCdr} vs ${otherCdr}). Prioritize it in the eye-care review.`;
  }

  let recTitle = overall.nextStepTitle;
  let recMessage = overall.nextStepBody;
  if (overall.key === "suspect") {
    const leftSuspect = leftStatus.key === "suspect";
    const rightSuspect = rightStatus.key === "suspect";
    if (leftSuspect && rightSuspect) {
      recTitle = "Review both eyes";
    } else if (leftSuspect) {
      recTitle = "Review left-eye result";
    } else {
      recTitle = "Review right-eye result";
    }
    recMessage = "Arrange an eye-care review. Compare both eyes with an eye specialist.";
  }

  return {
    leftStatus,
    rightStatus,
    overall,
    summarySentence,
    recTitle,
    recMessage,
  };
}

