function switchView(viewName) {
  state.currentView = viewName;

  const viewMap = {
    onboarding: "viewOnboarding",
    scan: "viewScan",
    review: "viewReview",
    report: "viewReport",
    detail: "viewEyeDetail",
  };

  Object.values(viewMap).forEach((id) => {
    document.getElementById(id).classList.remove("active");
  });
  document.getElementById(viewMap[viewName]).classList.add("active");

  // Update sidebar pills
  document.querySelectorAll(".stage-pill").forEach((btn) => {
    const target = btn.getAttribute("data-goto");
    const isMatch =
      target === viewName ||
      (target === "scan" && viewName === "review") ||
      (target === "report" && viewName === "detail");
    btn.classList.toggle("active", isMatch);
  });

  if (viewName === "scan") {
    updateScanUI();
    startCameraIfPossible();
  } else {
    stopCamera();
  }

  if (viewName === "review") {
    updateReviewUI();
  } else if (viewName === "report") {
    updateReportUI();
  } else if (viewName === "detail") {
    updateDetailUI();
  }
}

