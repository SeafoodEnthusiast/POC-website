async function startCameraIfPossible() {
  const video = document.getElementById("cameraVideo");
  const fallback = document.getElementById("cameraFallbackBackdrop");

  if (!navigator.mediaDevices || !navigator.mediaDevices.getUserMedia) {
    fallback.classList.remove("hidden");
    return;
  }

  try {
    const stream = await navigator.mediaDevices.getUserMedia({
      video: { facingMode: { ideal: "environment" }, width: { ideal: 1080 }, height: { ideal: 1080 } },
      audio: false,
    });
    state.cameraStream = stream;
    video.srcObject = stream;
    fallback.classList.add("hidden");
  } catch {
    // Camera unavailable or denied on desktop: show sample target preview gracefully
    fallback.classList.remove("hidden");
  }
}

function stopCamera() {
  if (state.cameraStream) {
    state.cameraStream.getTracks().forEach((t) => t.stop());
    state.cameraStream = null;
  }
}

function loadImageElement(src) {
  return new Promise((resolve, reject) => {
    const img = new Image();
    img.crossOrigin = "anonymous";
    img.onload = () => resolve(img);
    img.onerror = (e) => reject(e);
    img.src = src;
  });
}

function openReviewWithImage(imgObj, sampleKey = null) {
  state.selectedImageObj = imgObj;
  state.selectedImageSampleKey = sampleKey;
  state.reviewZoom = 1;
  state.reviewOffsetX = 0;
  state.reviewOffsetY = 0;
  state.cropMode = false;
  switchView("review");
}

function showIosAlert(title, message) {
  document.getElementById("iosAlertTitle").textContent = title;
  document.getElementById("iosAlertMessage").textContent = message;
  document.getElementById("iosAlertBackdrop").classList.remove("hidden");
}

